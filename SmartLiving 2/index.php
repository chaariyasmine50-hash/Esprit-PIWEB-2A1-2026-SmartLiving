<?php
declare(strict_types=1);

// ------------------------------------------------------------------
// 1. Secure session configuration (must be BEFORE session_start)
// ------------------------------------------------------------------
ini_set('session.use_strict_mode', '1');   // reject session IDs not generated by the server
ini_set('session.cookie_httponly', '1');   // cookie inaccessible to JavaScript (XSS protection)
ini_set('session.cookie_samesite', 'Lax'); // limit CSRF by restricting third-party cookies
// ini_set('session.cookie_secure', '1');  // uncomment if the site is served in HTTPS
session_start();

// ------------------------------------------------------------------
// 2. Session expiration after 30 minutes of inactivity
// ------------------------------------------------------------------
$sessionLifetime = 1800; // 30 minutes
if (isset($_SESSION['last_activity']) && (time() - $_SESSION['last_activity'] > $sessionLifetime)) {
    $_SESSION = [];
    session_destroy();
    session_start();
}
$_SESSION['last_activity'] = time();

// ------------------------------------------------------------------
// 3. HTTP security headers
// ------------------------------------------------------------------
header('X-Frame-Options: DENY');                 // anti clickjacking
header('X-Content-Type-Options: nosniff');       // prevents MIME-sniffing
header('Referrer-Policy: strict-origin-when-cross-origin');
header("Content-Security-Policy: default-src 'self'; style-src 'self' 'unsafe-inline'"); // limits XSS

// ------------------------------------------------------------------
// 4. Controllers
// ------------------------------------------------------------------
require_once __DIR__ . '/controllers/AuthController.php';
require_once __DIR__ . '/controllers/UserController.php';

$authController = new AuthController();
$userController = new UserController($authController);

// Re-check the logged-in account on EVERY request (not only at login):
// a deleted or blocked account is logged out at once, and a role changed
// by an admin takes effect immediately.
if (AuthController::isAuthenticated()) {
    $current = $authController->findById((int) $_SESSION['user_id']);
    if (!$current || $current->getStatus() === 'blocked') {
        $authController->logout();
        header('Location: index.php?action=login');
        exit;
    }
    $_SESSION['role']     = $current->getRole();
    $_SESSION['username'] = $current->getUsername();
}

// Small helper: redirect + stop
function redirect(string $action, string $extra = ''): void
{
    header('Location: index.php?action=' . $action . $extra);
    exit;
}

// ------------------------------------------------------------------
// 5. Routing
// ------------------------------------------------------------------
$action = $_GET['action'] ?? 'home';
$isPost = ($_SERVER['REQUEST_METHOD'] ?? 'GET') === 'POST';

switch ($action) {

    // ---------------- HOME ----------------
    case 'home':
        if (AuthController::isAuthenticated()) {
            redirect(($_SESSION['role'] ?? '') === 'admin' ? 'admin' : 'dashboard');
        }
        redirect('login');
        break;

    // ---------------- REGISTER ----------------
    case 'register':
        if (AuthController::isAuthenticated()) {
            redirect('dashboard');
        }
        $errors = [];
        $old = [];

        if ($isPost) {
            $errors = $authController->register($_POST);
            $old = [
                'first_name' => $_POST['first_name'] ?? '',
                'last_name'  => $_POST['last_name'] ?? '',
                'username'   => $_POST['username'] ?? '',
                'email'      => $_POST['email'] ?? '',
            ];

            if (empty($errors)) {
                redirect('login', '&registered=1');
            }
        }
        $csrfToken = $authController->getCsrfToken();
        require __DIR__ . '/views/register.php';
        break;

    // ---------------- LOGIN ----------------
    case 'login':
        if (AuthController::isAuthenticated()) {
            redirect('dashboard');
        }
        $errors = [];
        $old = [];

        if ($isPost) {
            $errors = $authController->login($_POST);
            $old = ['email' => $_POST['email'] ?? ''];

            if (empty($errors)) {
                redirect(($_SESSION['role'] ?? '') === 'admin' ? 'admin' : 'dashboard');
            }
        }
        $csrfToken = $authController->getCsrfToken();
        require __DIR__ . '/views/login.php';
        break;

    // ---------------- LOGOUT ----------------
    case 'logout':
        $authController->logout();
        redirect('login');
        break;

    // ---------------- USER SPACE (frontoffice) ----------------
    case 'dashboard':
        AuthController::requireAuth();

        $user = $authController->findById((int) $_SESSION['user_id']);
        if (!$user || $user->getStatus() === 'blocked') {
            $authController->logout();
            redirect('login');
        }
        $flash = AuthController::takeFlash();
        require __DIR__ . '/views/user_space.php';
        break;

    // ---------------- MY PROFILE: read + update (frontoffice) ----------------
    case 'profile':
        AuthController::requireAuth();

        $id = (int) $_SESSION['user_id'];
        $errors = [];
        $passwordErrors = [];
        $deleteErrors = [];

        if ($isPost) {
            $errors = $userController->update($id, $_POST, false);
            if (empty($errors)) {
                AuthController::flash('success', 'Your profile has been updated.');
                redirect('profile');
            }
        }
        $user = $userController->findById($id);
        if (!$user) {
            $authController->logout();
            redirect('login');
        }
        $old = $isPost ? $_POST : [];
        $flash = AuthController::takeFlash();
        $csrfToken = $authController->getCsrfToken();
        require __DIR__ . '/views/profile.php';
        break;

    // ---------------- CHANGE MY PASSWORD ----------------
    case 'password':
        AuthController::requireAuth();
        if (!$isPost) {
            redirect('profile');
        }
        $id = (int) $_SESSION['user_id'];
        $passwordErrors = $userController->changePassword($id, $_POST);
        if (empty($passwordErrors)) {
            AuthController::flash('success', 'Your password has been changed.');
            redirect('profile');
        }
        $errors = [];
        $deleteErrors = [];
        $user = $userController->findById($id);
        $old = [];
        $flash = null;
        $csrfToken = $authController->getCsrfToken();
        require __DIR__ . '/views/profile.php';
        break;

    // ---------------- DELETE MY ACCOUNT ----------------
    case 'account_delete':
        AuthController::requireAuth();
        if (!$isPost) {
            redirect('profile');
        }
        $id = (int) $_SESSION['user_id'];
        $deleteErrors = $userController->deleteOwnAccount($id, $_POST);
        if (empty($deleteErrors)) {
            $authController->logout();
            redirect('login', '&deleted=1');
        }
        $errors = [];
        $passwordErrors = [];
        $user = $userController->findById($id);
        $old = [];
        $flash = null;
        $csrfToken = $authController->getCsrfToken();
        require __DIR__ . '/views/profile.php';
        break;

    // ---------------- ADMIN SPACE (role: admin only - backoffice) ----------------
    case 'admin':
        AuthController::requireRole('admin');

        $user         = $authController->findById((int) $_SESSION['user_id']);
        $allUsers     = $authController->getAllUsers();
        $latestUsers  = $userController->latest(5);
        $totalUsers   = $authController->countAllUsers();
        $totalAdmins  = $authController->countByRole('admin');
        $totalRegular = $authController->countByRole('user');
        $totalBlocked = $authController->countByStatus('blocked');
        $flash = AuthController::takeFlash();

        require __DIR__ . '/views/admin_space.php';
        break;

    // ---------------- ADMIN: USERS LIST (read + search + filters) ----------------
    case 'admin_users':
        AuthController::requireRole('admin');

        $user   = $authController->findById((int) $_SESSION['user_id']);
        $q      = trim((string) ($_GET['q'] ?? ''));
        $role   = (string) ($_GET['role'] ?? '');
        $status = (string) ($_GET['status'] ?? '');
        $users  = $userController->search($q, $role, $status);
        $flash  = AuthController::takeFlash();
        $csrfToken = $authController->getCsrfToken();

        require __DIR__ . '/views/admin_users.php';
        break;

    // ---------------- ADMIN: CREATE USER ----------------
    case 'admin_user_create':
        AuthController::requireRole('admin');

        $user = $authController->findById((int) $_SESSION['user_id']);
        $errors = [];
        $old = ['role' => 'user', 'status' => 'active'];
        $editUser = null;

        if ($isPost) {
            $errors = $userController->create($_POST);
            if (empty($errors)) {
                AuthController::flash('success', 'The user has been created.');
                redirect('admin_users');
            }
            $old = $_POST;
        }
        $csrfToken = $authController->getCsrfToken();
        require __DIR__ . '/views/admin_user_form.php';
        break;

    // ---------------- ADMIN: EDIT USER (incl. role management) ----------------
    case 'admin_user_edit':
        AuthController::requireRole('admin');

        $user = $authController->findById((int) $_SESSION['user_id']);
        $id = (int) ($_GET['id'] ?? 0);
        $editUser = $userController->findById($id);
        if (!$editUser) {
            AuthController::flash('error', 'User not found.');
            redirect('admin_users');
        }
        $errors = [];
        $old = [
            'first_name' => $editUser->getFirstName(),
            'last_name'  => $editUser->getLastName(),
            'username'   => $editUser->getUsername(),
            'email'      => $editUser->getEmail(),
            'role'       => $editUser->getRole(),
            'status'     => $editUser->getStatus(),
            'points'     => (string) $editUser->getPoints(),
        ];

        if ($isPost) {
            $errors = $userController->update($id, $_POST, true);
            if (empty($errors)) {
                AuthController::flash('success', 'The user has been updated.');
                redirect('admin_users');
            }
            $old = array_merge($old, $_POST);
        }
        $csrfToken = $authController->getCsrfToken();
        require __DIR__ . '/views/admin_user_form.php';
        break;

    // ---------------- ADMIN: BLOCK / UNBLOCK USER ----------------
    case 'admin_user_toggle':
        AuthController::requireRole('admin');
        if ($isPost) {
            $errors = $userController->toggleStatus((int) ($_POST['id'] ?? 0), $_POST);
            AuthController::flash(empty($errors) ? 'success' : 'error', empty($errors) ? 'The account status has been changed.' : $errors[0]);
        }
        redirect('admin_users');
        break;

    // ---------------- ADMIN: DELETE USER ----------------
    case 'admin_user_delete':
        AuthController::requireRole('admin');
        if ($isPost) {
            $errors = $userController->delete((int) ($_POST['id'] ?? 0), $_POST);
            AuthController::flash(empty($errors) ? 'success' : 'error', empty($errors) ? 'The user has been deleted.' : $errors[0]);
        }
        redirect('admin_users');
        break;

    default:
        http_response_code(404);
        echo '404 - Page not found';
        break;
}
